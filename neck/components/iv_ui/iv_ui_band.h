/* Полоса рисования — внутренняя кухня iv_ui, наружу не выставляется.
 *
 * Всё рисование идёт в один буфер шириной в экран и высотой до
 * IV_UI_BAND_ROWS, а на панель уходит одной передачей. Своего буфера кадра
 * нет: 220 КБ на экран, который меняется на единицы процентов площади,
 * стоили бы больше, чем экономят.
 *
 * Координата y во всех функциях — внутри полосы, а не на экране; экранную
 * позицию задаёт только iv_band_flush(). */
#ifndef IV_UI_BAND_H
#define IV_UI_BAND_H

#include "iv_ui.h"

/* Открывает полосу высотой h и заливает её фоном. */
void iv_band_begin(int h, uint16_t bg);

/* Прямоугольник; всё, что вылезает за полосу или за экран, отсекается. */
void iv_band_rect(int x, int y, int w, int h, uint16_t color);

/* Текст масштабом scale (1 — клетка 6x8). Строчные приводятся к заглавным,
 * неизвестные знаки — к «?». */
void iv_band_text(int x, int y, int scale, uint16_t color, const char *s);

/* Ширина строки в точках — для выравнивания по центру и по правому краю. */
int iv_band_text_w(int scale, const char *s);

/* Выводит полосу на экран, начиная со строки screen_y. */
void iv_band_flush(int screen_y);

#endif /* IV_UI_BAND_H */
