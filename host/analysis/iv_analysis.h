/* Анализ сигнала для хостовых проверок и для tools/render.
 *
 * Только на компьютере: в прошивку это не идёт. Смысл — научиться отвечать на
 * вопрос «звучит ли это как смычок» цифрами, а не только ушами. У волны
 * Гельмгольца есть проверяемые признаки: устойчивый период, пилообразная форма
 * с одним изломом за период, спад гармоник около 6 дБ на октаву. Каждый из них
 * здесь измеряется. */
#ifndef IV_ANALYSIS_H
#define IV_ANALYSIS_H

#include <stddef.h>

double iv_an_peak(const float *x, size_t n);
double iv_an_rms(const float *x, size_t n);

/* Амплитуда синусоиды частоты hz (Гёрцель). Дешевле полного спектра, когда
 * интересны считанные частоты — например, уровни гармоник. */
double iv_an_mag(const float *x, size_t n, double sr, double hz);

/* Основной тон по автокорреляции в диапазоне lo..hi Гц; 0 — не нашёлся.
 * Максимум уточняется параболой по трём точкам, иначе разрешение упирается в
 * целые сэмплы: на 660 Гц один сэмпл лага это уже 26 центов. */
double iv_an_f0(const float *x, size_t n, double sr, double lo, double hi);

/* Насколько сигнал вообще периодичен: нормированная автокорреляция на лаге
 * периода, 1 — идеально. Это и есть мера «нота или скрип». */
double iv_an_periodicity(const float *x, size_t n, double sr, double f0);

/* Спектр по окну Ханна; mag заполняется на nfft/2 значений (амплитуды).
 * n должно быть не меньше nfft, nfft — степень двойки. */
void iv_an_spectrum(const float *x, size_t n, double *mag, size_t nfft);

/* Спектральный центроид, Гц — «яркость» одним числом.
 * Считает всю энергию подряд, поэтому шум смычка в него входит наравне с
 * тоном: для сравнения тембров при разной шумности он не годится. */
double iv_an_centroid(const float *x, size_t n, double sr, size_t nfft);

/* Наклон спектра: энергия гармоник 4..12 к энергии 1..3, в дБ. В отличие от
 * центроида смотрит только на частоты гармоник, а значит почти не замечает
 * шума — и меряет именно яркость тона. */
double iv_an_harmonic_tilt(const float *x, size_t n, double sr, double f0);

#endif /* IV_ANALYSIS_H */
